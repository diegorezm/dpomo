//! Color themes, loaded from TOML files.
//!
//! Built-ins live in `themes/*.toml` (embedded at compile time by `build.rs`);
//! users add their own to `<config dir>/dpomo/themes/`.

use std::path::{Path, PathBuf};

use egui::{Color32, CornerRadius, Stroke, Visuals};
use serde::{Deserialize, Serialize};

use crate::timer::Phase;

pub const CUSTOM: &str = "custom";

#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
pub struct Theme {
    #[serde(with = "hex")]
    pub background: Color32,
    /// Cards, buttons and the empty part of the ring.
    #[serde(with = "hex")]
    pub surface: Color32,
    #[serde(with = "hex")]
    pub text: Color32,
    #[serde(with = "hex")]
    pub muted: Color32,
    #[serde(with = "hex")]
    pub focus: Color32,
    #[serde(with = "hex")]
    pub short_break: Color32,
    #[serde(with = "hex")]
    pub long_break: Color32,
}

impl Default for Theme {
    fn default() -> Self {
        let (_, text) = builtin::BUILTIN
            .iter()
            .find(|(stem, _)| *stem == DEFAULT_FILE)
            .expect("default theme file is embedded");
        parse(text, DEFAULT_FILE).expect("default theme parses").1
    }
}

const fn rgb(hex: u32) -> Color32 {
    Color32::from_rgb((hex >> 16) as u8, (hex >> 8) as u8, hex as u8)
}

/// Generated by `build.rs`: `(file_stem, file_contents)` for `themes/*.toml`.
mod builtin {
    include!(concat!(env!("OUT_DIR"), "/builtin_themes.rs"));
}

const DEFAULT_FILE: &str = "rose-pine";
/// Display name of the default theme (the `name` in `themes/rose-pine.toml`).
pub const DEFAULT_NAME: &str = "Rosé Pine";

/// On-disk theme format: the colors plus an optional display name.
#[derive(Deserialize)]
struct ThemeFile {
    name: Option<String>,
    #[serde(flatten)]
    theme: Theme,
}

/// Parse a theme file. The display name falls back to the file stem.
fn parse(text: &str, stem: &str) -> Result<(String, Theme), toml::de::Error> {
    let file: ThemeFile = toml::from_str(text)?;
    Ok((file.name.unwrap_or_else(|| stem.to_owned()), file.theme))
}

/// Every available theme: built-ins plus `<config>/dpomo/themes/*.toml`.
/// A user theme with the same name as a built-in replaces it.
#[derive(Clone, Debug, Default)]
pub struct Themes {
    list: Vec<(String, Theme)>,
    /// Human-readable problems with user theme files, shown in settings.
    pub errors: Vec<String>,
}

impl Themes {
    pub fn dir() -> Option<PathBuf> {
        crate::config::Config::path().and_then(|p| Some(p.parent()?.join("themes")))
    }

    pub fn load() -> Self {
        let mut themes = Self::default();
        for (stem, text) in builtin::BUILTIN {
            match parse(text, stem) {
                Ok((name, theme)) => themes.insert(name, theme),
                Err(e) => themes
                    .errors
                    .push(format!("{stem}.toml ({}): {e}", crate::i18n::tr().builtin)),
            }
        }
        if let Some(dir) = Self::dir() {
            themes.load_dir(&dir);
        }
        // Dark themes first, then light; alphabetical inside each group.
        themes
            .list
            .sort_by_key(|(name, t)| (!t.is_dark(), name.to_lowercase()));
        themes
    }

    fn load_dir(&mut self, dir: &Path) {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        for path in entries.filter_map(|e| Some(e.ok()?.path())) {
            if path.extension().is_none_or(|e| e != "toml") {
                continue;
            }
            let file = path.file_name().unwrap_or_default().to_string_lossy();
            let stem = path.file_stem().unwrap_or_default().to_string_lossy();
            let result = std::fs::read_to_string(&path)
                .map_err(|e| e.to_string())
                .and_then(|text| parse(&text, &stem).map_err(|e| e.message().to_owned()));
            match result {
                Ok((name, theme)) => self.insert(name, theme),
                Err(e) => self.errors.push(format!("{file}: {e}")),
            }
        }
    }

    fn insert(&mut self, name: String, theme: Theme) {
        match self.list.iter_mut().find(|(n, _)| *n == name) {
            Some(slot) => slot.1 = theme,
            None => self.list.push((name, theme)),
        }
    }

    pub fn get(&self, name: &str) -> Option<Theme> {
        self.list.iter().find(|(n, _)| n == name).map(|(_, t)| *t)
    }

    pub fn iter(&self) -> impl Iterator<Item = (&str, Theme)> {
        self.list.iter().map(|(n, t)| (n.as_str(), *t))
    }

    /// Write `theme` as `<themes dir>/<slug>.toml`, returning the path.
    pub fn export(name: &str, theme: &Theme) -> std::io::Result<PathBuf> {
        #[derive(Serialize)]
        struct Out<'a> {
            name: &'a str,
            #[serde(flatten)]
            theme: &'a Theme,
        }
        let dir = Self::dir().ok_or_else(|| std::io::Error::other("no config dir"))?;
        std::fs::create_dir_all(&dir)?;
        let slug: String = name
            .chars()
            .map(|c| {
                if c.is_alphanumeric() {
                    c.to_ascii_lowercase()
                } else {
                    '-'
                }
            })
            .collect();
        let path = dir.join(format!("{slug}.toml"));
        let text = toml::to_string_pretty(&Out { name, theme }).map_err(std::io::Error::other)?;
        std::fs::write(&path, text)?;
        Ok(path)
    }
}

impl Theme {
    pub fn accent(&self, phase: Phase) -> Color32 {
        match phase {
            Phase::Focus => self.focus,
            Phase::ShortBreak => self.short_break,
            Phase::LongBreak => self.long_break,
        }
    }

    pub fn is_dark(&self) -> bool {
        let [r, g, b, _] = self.background.to_array();
        (0.299 * f32::from(r) + 0.587 * f32::from(g) + 0.114 * f32::from(b)) < 128.0
    }

    /// Push this theme into egui's global style. Cheap, but only call it when
    /// the theme actually changes.
    pub fn apply(&self, ctx: &egui::Context) {
        let dark = self.is_dark();
        let mut v = if dark {
            Visuals::dark()
        } else {
            Visuals::light()
        };

        v.panel_fill = self.background;
        v.window_fill = self.surface;
        // Text fields sit inside cards (surface), so give them a distinct well.
        v.extreme_bg_color = mix(self.surface, self.background, 0.6);
        v.faint_bg_color = self.surface;
        v.code_bg_color = self.surface;
        v.override_text_color = Some(self.text);
        v.hyperlink_color = self.focus;
        v.selection.bg_fill = self.focus.gamma_multiply(0.45);
        v.selection.stroke = Stroke::new(1.0, self.text);
        v.window_corner_radius = CornerRadius::same(14);
        v.window_stroke = Stroke::new(1.0, mix(self.surface, self.text, 0.08));

        let radius = CornerRadius::same(8);
        let w = &mut v.widgets;
        w.noninteractive.bg_fill = self.background;
        w.noninteractive.weak_bg_fill = self.background;
        w.noninteractive.bg_stroke = Stroke::new(1.0, self.surface);
        w.noninteractive.fg_stroke = Stroke::new(1.0, self.text);
        for (state, t) in [
            (&mut w.inactive, 0.07),
            (&mut w.hovered, 0.14),
            (&mut w.active, 0.20),
            (&mut w.open, 0.14),
        ] {
            let fill = mix(self.surface, self.text, t);
            state.bg_fill = fill;
            state.weak_bg_fill = fill;
            state.bg_stroke = Stroke::NONE;
            state.fg_stroke = Stroke::new(1.5, self.text);
            state.corner_radius = radius;
            state.expansion = 0.0;
        }
        // Slider rails, checkbox boxes, etc. use the inactive bg_fill.
        w.inactive.bg_fill = mix(self.surface, self.text, 0.14);

        let egui_theme = if dark {
            egui::Theme::Dark
        } else {
            egui::Theme::Light
        };
        ctx.set_theme(egui_theme);
        ctx.set_visuals_of(egui_theme, v);
        ctx.all_styles_mut(|s| {
            s.spacing.item_spacing = egui::vec2(8.0, 8.0);
            s.spacing.button_padding = egui::vec2(10.0, 5.0);
            s.spacing.interact_size.y = 26.0;
        });
    }
}

/// Linear blend between two colors, `t` in 0..=1.
pub fn mix(a: Color32, b: Color32, t: f32) -> Color32 {
    let l = |x: u8, y: u8| (f32::from(x) + (f32::from(y) - f32::from(x)) * t).round() as u8;
    Color32::from_rgba_unmultiplied(
        l(a.r(), b.r()),
        l(a.g(), b.g()),
        l(a.b(), b.b()),
        l(a.a(), b.a()),
    )
}

/// Serialize colors as `"#rrggbb"` so the config file stays readable.
mod hex {
    use egui::Color32;
    use serde::{Deserialize, Deserializer, Serializer, de::Error};

    pub fn serialize<S: Serializer>(c: &Color32, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_str(&format!("#{:02x}{:02x}{:02x}", c.r(), c.g(), c.b()))
    }

    pub fn deserialize<'de, D: Deserializer<'de>>(d: D) -> Result<Color32, D::Error> {
        let s = String::deserialize(d)?;
        let digits = s.trim_start_matches('#');
        let n = u32::from_str_radix(digits, 16)
            .ok()
            .filter(|_| digits.len() == 6)
            .ok_or_else(|| {
                D::Error::custom(crate::i18n::fill(
                    crate::i18n::tr().invalid_color,
                    &[("value", &format!("{s:?}"))],
                ))
            })?;
        Ok(super::rgb(n))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn builtins() -> Vec<(String, Theme)> {
        builtin::BUILTIN
            .iter()
            .map(|(stem, text)| parse(text, stem).unwrap_or_else(|e| panic!("{stem}.toml: {e}")))
            .collect()
    }

    #[test]
    fn builtin_themes_parse_with_unique_names() {
        let all = builtins();
        assert!(all.len() >= 2);
        for (i, (name, _)) in all.iter().enumerate() {
            assert_ne!(name, CUSTOM);
            assert!(
                all[i + 1..].iter().all(|(n, _)| n != name),
                "duplicate {name}"
            );
        }
    }

    #[test]
    fn default_theme_name_matches_its_file() {
        let all = builtins();
        let (_, t) = all
            .iter()
            .find(|(n, _)| n == DEFAULT_NAME)
            .expect("default exists");
        assert_eq!(*t, Theme::default());
    }

    #[test]
    fn light_themes_are_detected() {
        let all = builtins();
        let get = |n: &str| all.iter().find(|(name, _)| name == n).unwrap().1;
        assert!(get("Rosé Pine").is_dark());
        assert!(!get("Latte").is_dark());
    }

    #[test]
    fn user_dir_overrides_and_reports_errors() {
        let dir = std::env::temp_dir().join(format!("dpomo-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let nord = builtin::BUILTIN
            .iter()
            .find(|(s, _)| *s == "nord")
            .unwrap()
            .1;
        let custom = nord.replace("#bf616a", "#000000");
        std::fs::write(dir.join("my-nord.toml"), custom).unwrap();
        std::fs::write(dir.join("broken.toml"), "background = \"red\"").unwrap();
        std::fs::write(dir.join("notes.txt"), "ignored").unwrap();

        let mut themes = Themes::default();
        themes.insert("Nord".into(), Theme::default());
        themes.load_dir(&dir);
        std::fs::remove_dir_all(&dir).unwrap();

        assert_eq!(themes.get("Nord").unwrap().focus, Color32::BLACK);
        assert_eq!(themes.errors.len(), 1, "{:?}", themes.errors);
        assert!(themes.errors[0].starts_with("broken.toml"));
    }

    #[test]
    fn name_falls_back_to_file_stem() {
        let text = builtin::BUILTIN[0]
            .1
            .lines()
            .filter(|l| !l.starts_with("name"))
            .collect::<Vec<_>>()
            .join("\n");
        assert_eq!(parse(&text, "meu-tema").unwrap().0, "meu-tema");
    }
}
